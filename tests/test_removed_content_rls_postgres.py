def _read(name: str) -> str:
    return (MIGRATIONS / name).read_text(encoding="utf-8")


def _initial_schema_event_chats() -> str:
    """The event_chats CREATE TABLE of the initial schema (what production really has:
    id GENERATED BY DEFAULT, event_id nullable, sender_id -> profiles ON DELETE CASCADE)."""
    m = re.search(r"CREATE TABLE IF NOT EXISTS public\.event_chats \(.*?\);",
                  _read("20260101000000_initial_schema.sql"), re.S)
    assert m, "event_chats DDL not found in the initial schema"
    return m.group(0)


def _enable_rls_subset() -> str:
    text = re.sub(r"--[^\n]*", "", _read("20260411120000_enable_rls.sql"))
    keep = [s for s in text.split(";") if re.search(r"public\.(events|event_chats)\b", s)]
    return ";\n".join(keep) + ";"


