"""PostgreSQL behaviour test for the removed-content RLS guards migration.

HOW TO RUN (needs a SCRATCH PostgreSQL database, never the real one, and a role
allowed to CREATE ROLE / SET ROLE, e.g. a superuser on a throwaway local server):

    REMOVED_CONTENT_RLS_TEST_DATABASE_URL=postgresql://postgres:pw@localhost:5432/scratch \
        pytest tests/test_removed_content_rls_postgres.py -q

Skipped when the variable is unset or psycopg2 is missing. Also skipped when the
database already has public.events (so nothing real is ever touched).

Isolation: everything (stand-in Supabase pieces, tables, data, migrations) runs
inside ONE transaction that is rolled back at teardown, so the database is left
unchanged.

Why a subset of the real migrations: the full chain needs Supabase-only
extensions (pgvector, realtime publication, ...). We therefore create minimal
stand-ins (roles anon/authenticated/service_role, auth.users, auth.uid(),
auth.jwt(), auth.role(), and bare profiles/events/event_participants tables) and
apply the REAL files: the event_chats table DDL copied verbatim from 20260101000000
(initial schema), then 20260422161000 (its CREATE TABLE IF NOT EXISTS is skipped
because the table exists, exactly as in production, while its indexes and policies
still apply), the events/event_chats
statements of 20260411120000 (enable_rls; filtered because it references many
tables not needed here, and applied after event_chats exists), 20260424142000,
20261026120000 and finally 20261111120000 (the guards).
"""
import json
import os
import re
import uuid
from pathlib import Path

import pytest

DB_URL = os.environ.get("REMOVED_CONTENT_RLS_TEST_DATABASE_URL")
pytestmark = pytest.mark.skipif(not DB_URL, reason="REMOVED_CONTENT_RLS_TEST_DATABASE_URL not set")

MIGRATIONS = Path(__file__).resolve().parents[1] / "supabase" / "migrations"

STANDINS = """
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin; end if;
end $$;
-- Supabase's service_role has BYPASSRLS (ALTER ROLE is transactional, rolled back at teardown).
alter role service_role bypassrls;
create schema if not exists auth;
create table if not exists auth.users (id uuid primary key);
create or replace function auth.jwt() returns jsonb language sql stable as
  $$ select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb $$;
create or replace function auth.uid() returns uuid language sql stable as
  $$ select nullif(auth.jwt() ->> 'sub', '')::uuid $$;
create or replace function auth.role() returns text language sql stable as
  $$ select auth.jwt() ->> 'role' $$;
create table public.profiles (id uuid primary key references auth.users(id), role varchar default 'user');
create table public.events (
  id uuid primary key default gen_random_uuid(), title varchar not null,
  created_by uuid references public.profiles(id));
create table public.event_participants (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references public.profiles(id), event_id uuid references public.events(id));
"""

GRANTS = """
grant usage on schema public, auth to anon, authenticated, service_role;
grant all on all tables in schema public to anon, authenticated, service_role;
grant select on auth.users to authenticated;
grant execute on all functions in schema auth to anon, authenticated, service_role;
"""

USER, OTHER, ADMIN = (str(uuid.uuid4()) for _ in range(3))
