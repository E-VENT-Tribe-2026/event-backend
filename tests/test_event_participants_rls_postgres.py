# 9: direct writes are denied (restrictive write-lock policies)
def _row_exists(cur, event_id, user_id):
    """As the table owner (bypasses RLS)."""
    cur.execute("reset role")
    cur.execute("select count(*) from public.event_participants where event_id = %s and user_id = %s",
                (event_id, user_id))
    return cur.fetchone()[0] == 1


def _assert_insert_denied(cur, sql, params):
    import psycopg2.errors
    cur.execute("savepoint denied")
    with pytest.raises(psycopg2.errors.InsufficientPrivilege) as exc:
        cur.execute(sql, params)
    assert exc.value.pgcode == "42501"
    assert "row-level security" in str(exc.value)
    cur.execute("rollback to savepoint denied")


