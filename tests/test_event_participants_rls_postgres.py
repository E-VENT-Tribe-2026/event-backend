def act_as(cur, uid, aal="aal1"):
    cur.execute("set local role authenticated")
    claims = json.dumps({"sub": uid, "role": "authenticated", "aal": aal})
    cur.execute("select set_config('request.jwt.claims', %s, true)", (claims,))


def act_as_anon(cur):
    cur.execute("set local role anon")
    cur.execute("select set_config('request.jwt.claims', %s, true)", (json.dumps({"role": "anon"}),))


def rows(cur, event_id=EV):
    cur.execute(LIST_SQL, (event_id,))
    return cur.fetchall()


def users(cur, event_id=EV):
    return {str(r[0]) for r in rows(cur, event_id)}


def control_rows(cur, event_id=EV):
    """As the table owner (bypasses RLS): the fixture really has rows for the event."""
    cur.execute("reset role")
    cur.execute("select count(*) from public.event_participants where event_id = %s", (event_id,))
    n = cur.fetchone()[0]
    assert n > 0
    return n


def act_as_service(cur):
    """Stand-in for the backend: service_role has BYPASSRLS (set in STANDINS)."""
    cur.execute("set local role service_role")
    cur.execute("select set_config('request.jwt.claims', %s, true)",
                (json.dumps({"role": "service_role"}),))


def owner_insert(cur, user_id, event_id=EV, status="registered"):
    """Seed a participant row as the owner/superuser (bypasses RLS)."""
    cur.execute("reset role")
    cur.execute("insert into public.event_participants(user_id, event_id, status) values (%s,%s,%s)",
                (user_id, event_id, status))


def drop_guard(cur):
    cur.execute("reset role")
    cur.execute('drop policy "event_participants_read_guard" on public.event_participants')


def drop_baseline_chat_policies(cur):
    cur.execute("reset role")
    cur.execute('drop policy "Auth read access for event_chats" on public.event_chats')
    cur.execute('drop policy "Auth all access for event_chats" on public.event_chats')


