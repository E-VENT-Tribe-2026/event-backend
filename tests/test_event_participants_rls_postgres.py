def test_applying_the_migration_twice_keeps_exactly_four_policies(cur):
    cur.execute("reset role")
    cur.execute("savepoint idem")
    cur.execute((MIGRATIONS / NEW_MIGRATION).read_text(encoding="utf-8"))
    cur.execute("select policyname, permissive, cmd from pg_policies "
                "where schemaname = 'public' and tablename = 'event_participants'")
    got = cur.fetchall()
    ours = sorted(r for r in got if r[0].startswith("event_participants_"))
    assert ours == sorted([
        ("event_participants_read_guard", "RESTRICTIVE", "SELECT"),
        ("event_participants_no_direct_insert", "RESTRICTIVE", "INSERT"),
        ("event_participants_no_direct_update", "RESTRICTIVE", "UPDATE"),
        ("event_participants_no_direct_delete", "RESTRICTIVE", "DELETE"),
    ])
    names = {r[0] for r in got}
    assert {"Auth read access for event_participants", "Auth all access for event_participants"} <= names
    assert len(got) == 6
    cur.execute("rollback to savepoint idem")


