"""PostgreSQL behaviour test for the event_participants read guard and write lock (ticket #257).

The migration adds a RESTRICTIVE read guard (SELECT) and three RESTRICTIVE write-lock
policies (no direct INSERT/UPDATE/DELETE for anon/authenticated). The stand-in
service_role is given BYPASSRLS (as in Supabase), so backend writes keep working.
All fixture rows are seeded as the owner/superuser, never through user writes.

HOW TO RUN (needs a SCRATCH PostgreSQL database, never the real one, and a role
allowed to CREATE ROLE / SET ROLE, e.g. a superuser on a throwaway local server):

    EVENT_PARTICIPANTS_RLS_TEST_DATABASE_URL=postgresql://postgres:pw@localhost:5432/scratch \
        pytest tests/test_event_participants_rls_postgres.py -q

Skipped when the variable is unset or psycopg2 is missing. Also skipped when the
database already has public.events (so nothing real is ever touched).

Everything runs inside ONE transaction rolled back at teardown. Stand-ins: roles
anon/authenticated/service_role, auth.users, auth.uid()/jwt()/role(). Tables mirror
the production DDL of 20260101000000 (profiles, events, event_participants,
event_chats). REAL files applied: the events/event_participants/event_chats
statements of 20260411120000 (enable_rls), 20260422161000 (event_chats policies),
and the new 20261112120000 migration (which itself defines is_administrator).
"""
