def test_event_without_creator_hides_from_anon_null_equals_null(cur):
    # created_by IS NULL and anon's auth.uid() is NULL: NULL = NULL is not true, so the
    # organizer arm must not match. A permissive anon policy (undone by the savepoint)
    # makes only the restrictive guard decide.
    control_rows(cur, EV_NOORG)
