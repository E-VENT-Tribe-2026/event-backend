-- Signup is invitation-only. An administrator emails a one-time code; the
-- invited person must enter that code before they can register.
--
-- Only the backend (service role) reads and writes this table.
-- Idempotent and safe to re-run.
--
-- Rollback (run manually):
--   drop table if exists public.registration_invites;
-- =============================================================================

create table if not exists public.registration_invites (
  id          bigint generated by default as identity primary key,
  email       text not null,
  code_hash   text not null,
  invited_by  uuid references public.profiles(id) on delete set null,
  expires_at  timestamptz not null,
  used_at     timestamptz,
  used_by     uuid references public.profiles(id) on delete set null,
  created_at  timestamptz not null default now()
);

create unique index if not exists registration_invites_open_email_uniq
  on public.registration_invites (email)
  where used_at is null;

create index if not exists registration_invites_email_idx
  on public.registration_invites (email, created_at desc);

alter table public.registration_invites enable row level security;
revoke all on public.registration_invites from anon, authenticated;
