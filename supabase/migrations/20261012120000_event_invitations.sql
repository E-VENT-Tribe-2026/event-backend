-- 1. Invitations
create table if not exists public.event_invitations (
  id          bigint generated by default as identity primary key,
  event_id    uuid not null references public.events(id) on delete cascade,
  inviter_id  uuid not null references public.profiles(id) on delete cascade,
  invitee_id  uuid not null references public.profiles(id) on delete cascade,
  created_at  timestamptz not null default now(),
  constraint event_invitations_not_self check (inviter_id <> invitee_id),
  constraint event_invitations_one_per_inviter unique (event_id, inviter_id, invitee_id)
);

create index if not exists event_invitations_invitee_idx
  on public.event_invitations (invitee_id, created_at desc);

create index if not exists event_invitations_event_invitee_idx
  on public.event_invitations (event_id, invitee_id);

-- Only the backend (service role) reads and writes invitations: no policies.
alter table public.event_invitations enable row level security;

-- 2. Link notifications to invitations
alter table public.notifications
  add column if not exists invitation_id bigint null
  references public.event_invitations(id) on delete cascade;

create index if not exists notifications_invitation_id_idx
  on public.notifications (invitation_id);

-- 3. Remove invitations when the invited user joins the event
create or replace function public.remove_invitations_on_join()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.event_invitations
  where event_id = new.event_id
    and invitee_id = new.user_id;
  return new;
end;
$$;

drop trigger if exists event_participants_remove_invitations on public.event_participants;
create trigger event_participants_remove_invitations
  after insert on public.event_participants
  for each row execute function public.remove_invitations_on_join();

-- 4. Remove invitations when the event is cancelled
create or replace function public.remove_invitations_on_cancel()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'cancelled' and old.status is distinct from 'cancelled' then
    delete from public.event_invitations where event_id = new.id;
  end if;
  return new;
end;
$$;

drop trigger if exists events_remove_invitations_on_cancel on public.events;
create trigger events_remove_invitations_on_cancel
  after update of status on public.events
  for each row execute function public.remove_invitations_on_cancel();

-- 5. Remove invitations between two users when their friendship ends
create or replace function public.remove_invitations_on_unfriend()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.event_invitations
  where (inviter_id = old.user_id and invitee_id = old.friend_id)
     or (inviter_id = old.friend_id and invitee_id = old.user_id);
  return old;
end;
$$;

drop trigger if exists friendships_remove_invitations on public.friendships;
create trigger friendships_remove_invitations
  after delete on public.friendships
  for each row execute function public.remove_invitations_on_unfriend();

-- 6. Called by the blocking code (#184) when one user blocks another
create or replace function public.remove_invitations_for_block(user_a uuid, user_b uuid)
returns void
language sql
security definer
set search_path = public
as $$
  delete from public.event_invitations i
  using public.events e
  where i.event_id = e.id
    and (
         (i.invitee_id = user_a and e.created_by = user_b)
      or (i.invitee_id = user_b and e.created_by = user_a)
      or (i.inviter_id = user_a and i.invitee_id = user_b)
      or (i.inviter_id = user_b and i.invitee_id = user_a)
    );
$$;

-- Only the backend may call it, not signed-in users or visitors through the API.
revoke execute on function public.remove_invitations_for_block(uuid, uuid) from public, anon, authenticated;
grant execute on function public.remove_invitations_for_block(uuid, uuid) to service_role;