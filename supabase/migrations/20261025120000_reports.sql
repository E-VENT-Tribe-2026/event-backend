create table if not exists public.reports (
  id               bigint generated by default as identity primary key,
  reporter_id      uuid references public.profiles(id) on delete set null,
  target_type      text not null,
  event_id         uuid references public.events(id) on delete set null,
  reported_user_id uuid references public.profiles(id) on delete set null,
  message_id       bigint,
  reason           text not null,
  description      text,
  origin           text not null,
  status           text not null default 'open',
  chat_context     jsonb,
  created_at       timestamptz not null default now(),
  constraint reports_target_type_check check (target_type in ('event', 'user', 'message')),
  constraint reports_reason_check check (
    reason in ('spam', 'inappropriate_content', 'harassment_or_hate', 'scam_or_fraud', 'misleading_event', 'other')
  ),
  constraint reports_origin_check check (origin in ('event_details', 'profile', 'event_chat')),
  constraint reports_status_check check (status in ('open', 'dismissed', 'action_taken')),
  -- Same limit as REPORT_DESCRIPTION_MAX_LENGTH in app/core/input_limits.py; the reason Other needs a description.
  constraint reports_description_check check (
    (description is null or char_length(btrim(description)) between 1 and 1000)
    and (reason <> 'other' or description is not null)
  ),
  -- What each kind of report points at. event_id and reported_user_id may become null later
  -- (on delete set null); the backend always sets them when it creates a report.
  constraint reports_target_columns_check check (
    (target_type = 'event'   and message_id is null and reported_user_id is null)
    or (target_type = 'user'    and event_id is null and message_id is null)
    or (target_type = 'message' and message_id is not null)
  ),
  constraint reports_misleading_event_only check (reason <> 'misleading_event' or target_type = 'event'),
  constraint reports_chat_context_origin check (chat_context is null or origin = 'event_chat')
);

