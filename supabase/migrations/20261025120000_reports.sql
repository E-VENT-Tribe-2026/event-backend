-- One open report per reporter and item.
create unique index if not exists reports_open_event_uniq
  on public.reports (reporter_id, event_id)
  where status = 'open' and target_type = 'event';

create unique index if not exists reports_open_user_uniq
  on public.reports (reporter_id, reported_user_id)
  where status = 'open' and target_type = 'user';

create unique index if not exists reports_open_message_uniq
  on public.reports (reporter_id, message_id)
  where status = 'open' and target_type = 'message';

-- Review lists (report review ticket): open reports, newest first.
create index if not exists reports_status_created_idx
  on public.reports (status, created_at desc);

