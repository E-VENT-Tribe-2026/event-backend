-- 1. Tiers
CREATE TABLE IF NOT EXISTS public.tiers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR NOT NULL,
    features_array VARCHAR[],
    price BIGINT DEFAULT 0,
    frequency VARCHAR,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 2. Payment Methods
CREATE TABLE IF NOT EXISTS public.payment_methods (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR NOT NULL,
    description TEXT,
    keys VARCHAR[],
    values_for_keys TEXT[],
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 3. Profiles (references auth.users and tiers)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name TEXT,
    phone VARCHAR,
    avatar_url TEXT,
    bio TEXT,
    role VARCHAR DEFAULT 'user',
    visibility VARCHAR DEFAULT 'public',
    is_verified BOOLEAN DEFAULT false,
    latitude NUMERIC,
    longitude NUMERIC,
    tier_id UUID REFERENCES public.tiers(id) ON DELETE SET NULL,
    gender TEXT,
    interests TEXT[],
    dob DATE,
    profile_status VARCHAR,
    account_type TEXT NOT NULL DEFAULT 'basic',
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

DO $$ BEGIN
    ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS interest_embedding vector;
EXCEPTION WHEN OTHERS THEN
    NULL;
END $$;

-- 4. Events (references profiles)
CREATE TABLE IF NOT EXISTS public.events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    title VARCHAR NOT NULL,
    description TEXT,
    category VARCHAR,
    cost BIGINT DEFAULT 0,
    max_capacity BIGINT,
    status VARCHAR DEFAULT 'draft',
    start_datetime TIMESTAMPTZ,
    end_datetime TIMESTAMPTZ,
    location_name VARCHAR,
    latitude NUMERIC,
    longitude NUMERIC,
    created_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    qr_link TEXT,
    privacy VARCHAR DEFAULT 'public',
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

DO $$ BEGIN
    ALTER TABLE public.events ADD COLUMN IF NOT EXISTS event_embedding vector(1024);
EXCEPTION WHEN OTHERS THEN
    NULL;
END $$;

-- 5. Tags
CREATE TABLE IF NOT EXISTS public.tags (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR NOT NULL
);

-- 6. Event Tags
CREATE TABLE IF NOT EXISTS public.event_tags (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    event_id UUID REFERENCES public.events(id) ON DELETE CASCADE,
    tag_id BIGINT REFERENCES public.tags(id) ON DELETE CASCADE
);

-- 7. Event Participants
CREATE TABLE IF NOT EXISTS public.event_participants (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    event_id UUID REFERENCES public.events(id) ON DELETE CASCADE,
    status VARCHAR DEFAULT 'registered',
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 8. Invoices
CREATE TABLE IF NOT EXISTS public.invoices (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    total_amount BIGINT NOT NULL,
    payment_date TIMESTAMPTZ,
    subscription_tier UUID REFERENCES public.tiers(id) ON DELETE SET NULL,
    payment_method_id UUID REFERENCES public.payment_methods(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 9. Preferences
CREATE TABLE IF NOT EXISTS public.preferences (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    profile_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    interest TEXT,
    updated_at TIMESTAMPTZ DEFAULT now()
);

DO $$ BEGIN
    ALTER TABLE public.preferences ADD COLUMN IF NOT EXISTS interest_embedding vector(1536);
EXCEPTION WHEN OTHERS THEN
    NULL;
END $$;

-- 10. Logs
CREATE TABLE IF NOT EXISTS public.logs (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    type VARCHAR,
    description TEXT,
    values TEXT[],
    created_by_id UUID,
    table_id UUID,
    entity_id VARCHAR,
    created_date TIMESTAMPTZ DEFAULT now(),
    entity_type TEXT
);

-- 11. AI Conversations
CREATE TABLE IF NOT EXISTS public.ai_conversations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    title TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- 12. AI Messages
CREATE TABLE IF NOT EXISTS public.ai_messages (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    conversation_id UUID NOT NULL REFERENCES public.ai_conversations(id) ON DELETE CASCADE,
    role TEXT NOT NULL,
    content TEXT NOT NULL,
    metadata JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 13. Friend Requests (Foundational table for Issue #181)
CREATE TABLE IF NOT EXISTS public.friend_requests (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    initiator_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    receiver_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    status VARCHAR DEFAULT 'pending',
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 14. Friendships (Foundational table for Issue #181)
CREATE TABLE IF NOT EXISTS public.friendships (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    friend_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    status VARCHAR DEFAULT 'active',
    origin UUID,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- 15. Event Chats (Foundational table for RLS policies)
CREATE TABLE IF NOT EXISTS public.event_chats (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    event_id UUID REFERENCES public.events(id) ON DELETE CASCADE,
    sender_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now()
);
